def get_category_keywords(category_type: str, category_name: str) -> list:
    """
    获取指定分类的关键词列表。

    Args:
        category_type: 分类类型（interests/roles/values/cognitive_styles/mbti）
        category_name: 分类名称

    Returns:
        list: 关键词列表
    """
    categories = get_all_categories().get(category_type, {})
    if category_type == "mbti":
        return [categories.get(category_name, "")]
    if category_type == "cognitive_styles":
        return [categories.get(category_name, "")]
    return categories.get(category_name, [])